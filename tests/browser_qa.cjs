// Optional browser workflow checks. Requires Playwright or playwright-core.
// Run against a demo server: LUMEN_QA_URL=http://127.0.0.1:8876 node tests/browser_qa.cjs
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? {executablePath: process.env.CHROMIUM_EXECUTABLE} : {})});
  const page = await browser.newPage({viewport: {width: 1440, height: 1080}, deviceScaleFactor: 1});
  const errors = [];
  const external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith(base)) external.push(r.url()); });
  const base = process.env.LUMEN_QA_URL || 'http://127.0.0.1:8876';
  try {
    let bootRequests = 0;
    await page.route('**/api/state', async route => {
      const response = await route.fetch();
      const body = await response.json();
      if (bootRequests === 0) body.version = '1.0.0';
      if (bootRequests === 1) body.layout[0][0].height = undefined;
      bootRequests++;
      await route.fulfill({response, json: body});
    });
    await page.goto(base, {waitUntil: 'networkidle'});
    assert.equal(await page.locator('.key').count(), 0, 'Do not draw an incompatible layout');
    assert.match(await page.locator('#connection-banner').textContent(), /finishing an update/);
    await page.waitForFunction(() => document.querySelectorAll('.key').length === 101, null, {timeout: 12000});
    assert.ok(bootRequests >= 3, 'Recover from both old API versions and incomplete layout metadata');
    await page.unroute('**/api/state');
    assert.equal(await page.locator('.key').count(), 101);
    assert.equal(await page.locator('.theme-card').count(), 30);
    assert.equal(await page.locator('.keyboard-row').first().locator('.key').count(), 19);
    // Validate physical alignment before applying the decorative perspective.
    await page.locator('.keyboard-shell').evaluate(el => { el.style.transform = 'none'; });
    const plus = await page.locator('[data-key=num_plus]').boundingBox();
    const seven = await page.locator('[data-key=num7]').boundingBox();
    const four = await page.locator('[data-key=num4]').boundingBox();
    assert.ok(Math.abs(plus.y-seven.y)<1);
    assert.ok(Math.abs(plus.y+plus.height-four.y-four.height)<1);
    const up = await page.locator('[data-key=up]').boundingBox();
    const down = await page.locator('[data-key=down]').boundingBox();
    assert.ok(Math.abs(up.x+up.width/2-down.x-down.width/2)<1);
    await page.locator('.keyboard-shell').evaluate(el => { el.style.transform = ''; });
    await page.locator('[data-filter=Gaming]').click();
    assert.equal(await page.locator('.theme-card').count(), 6);
    await page.getByRole('button', {name: 'Night runner Gaming'}).click();
    await page.waitForTimeout(200);
    assert.equal(await page.locator('[data-key=w]').evaluate(el => el.style.getPropertyValue('--key-color')), '#00ff85');
    assert.equal(await page.locator('[data-key=h]').evaluate(el => el.style.getPropertyValue('--key-color')), '#020306');
    assert.equal(await page.locator('.theme-card.selected .mini-key[data-slot="21"]').evaluate(el => el.style.getPropertyValue('--mini-color')), '#00ff85');
    await page.locator('#background').fill('0');
    await page.waitForTimeout(200);
    assert.equal(await page.locator('[data-key=h]').evaluate(el => el.style.getPropertyValue('--key-color')), '#000000');
    assert.equal(await page.locator('[data-key=w]').evaluate(el => el.style.getPropertyValue('--key-color')), '#00ff85');
    await page.locator('[data-filter=All]').click();
    await page.locator('#theme-search').fill('Dracula');
    assert.equal(await page.locator('.theme-card').count(), 1);
    await page.locator('#theme-search').fill('');
    await page.locator('[data-filter=Palette]').click();
    assert.equal(await page.locator('.theme-card').count(), 7);
    await page.locator('[data-filter=All]').click();
    await page.getByRole('button', {name: 'Synthwave Gradient'}).click();
    await page.waitForTimeout(150);
    assert.equal(await page.locator('#design-name').textContent(), 'Synthwave');
    await page.locator('#brightness').fill('37');
    assert.equal(await page.locator('#brightness-value').textContent(), '37%');
    await page.locator('#paint-toggle').click();
    await page.locator('#brush-color').fill('#ff0000');
    await page.getByRole('button', {name: 'Paint A key', exact: true}).click();
    await page.waitForTimeout(200);
    assert.match(await page.locator('#paint-help').textContent(), /1 key customized/);
    assert.equal(await page.getByRole('button', {name: 'Paint A key', exact: true}).evaluate(el => el.style.getPropertyValue('--key-color')), '#ff0000');
    await page.locator('#save-profile').click();
    await page.locator('#profile-name').fill('Browser QA <profile>');
    await page.locator('#profile-form button[type=submit]').click();
    await page.waitForFunction(() => !document.getElementById('save-dialog').open);
    await page.locator('[data-page=library]').click();
    const card = page.locator('.profile-card').filter({hasText: 'Browser QA <profile>'}).last();
    assert.equal(await card.locator('h2').textContent(), 'Browser QA <profile>');
    await card.getByRole('button', {name: 'Open in studio'}).click();
    assert.equal(await page.locator('#design-name').textContent(), 'Browser QA <profile>');
    await page.locator('#apply-remember').click();
    await page.waitForFunction(() => document.getElementById('apply-remember').disabled === false);
    await page.locator('[data-page=startup]').click();
    assert.equal(await page.locator('#startup-toggle').isChecked(), true);
    await page.locator('#startup-toggle').uncheck();
    await page.waitForFunction(() => document.getElementById('startup-toggle').disabled === false);
    assert.equal(await page.locator('#startup-toggle').isChecked(), false);
    await page.locator('[data-page=library]').click();
    page.once('dialog', dialog => dialog.accept());
    await page.locator('.profile-card').filter({hasText: 'Browser QA <profile>'}).last().getByRole('button', {name: 'Delete Browser QA <profile>'}).click();
    await page.waitForTimeout(150);
    assert.equal(await page.locator('.profile-card').filter({hasText: 'Browser QA <profile>'}).count(), 0);
    await page.locator('[data-page=studio]').click();
    await page.locator('[data-filter=Animated]').click();
    assert.equal(await page.locator('.theme-card').count(), 2);
    await page.locator('[data-filter=All]').click();
    await page.getByRole('button', {name: 'Aurora Gradient'}).click();
    await page.waitForTimeout(200);
    await page.screenshot({path: path.join(__dirname, '../docs/studio.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Page should fit a mobile viewport');
    assert.equal(await page.locator('#apply-remember').isVisible(), true);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log('Browser QA passed: 30 themes, physical key geometry, gaming contrast, background glow, exact thumbnails, search, painting, profiles, startup settings and mobile layout; no JavaScript errors or external requests.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
